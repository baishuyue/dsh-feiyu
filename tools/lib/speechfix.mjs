// speechfix —— 她"嘴瓢"的两类硬伤兜底（10-25 实锤过两回）
//
// ① 分享卡片：「主人发的这个我看不到内容呀，链接没打开」——主人当场无语。
//    根因不是模型不会，是占位符（[分享视频]）本来就拿不到正文，她只能顺着说"看不见"。
//    正确姿势：主人分享的是"给你的东西"，顺着他的感想接，想知道细节就直接问标题。
// ② 时间说法不在这支里（见 timefix.mjs）。

const BLIND = /看不到|看不见|打不开|没打开|内容是空|内容为空|显示不出|没显示出来|空白的?呀|链接(坏|失效)/

/** 这句是不是在"喊看不见"。 */
export function looksBlind(text) {
  return BLIND.test(String(text ?? ''))
}

/** 兜底改写：把"看不到内容"那半句换成"问标题"，其余原样保留。 */
export function askInstead(text) {
  let s = String(text ?? '')
  if (!looksBlind(s)) return s
  s = s.replace(/[^。！？\n]*(?:看不到|看不见|打不开|没打开|内容是空|内容为空|显示不出|没显示出来|空白的?呀|链接(?:坏|失效))[^。！？\n]*[。！？]?/g, '')
  s = s.replace(/^\s*[\n。，、]+/, '').trim()
  return s || '分享的哪个呀，标题给我看看，我馋着呢'
}

/** 给 prompt 用的一句硬约束（分享/卡片场景）。 */
export function noBlindHint() {
  return '（主人分享的是**给你的东西**：你只拿到占位符或一句感想，这是正常的。'
    + '顺着他说的话自然接一句就行；真想知道细节就问"分享的哪个呀，标题给我看看"。'
    + '**绝对不要**说"看不到内容""链接打不开""内容是空的""我这边显示不出来"这类话。）'
}

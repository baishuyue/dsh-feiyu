// speechfix —— 她"嘴瓢"的两类硬伤兜底（10-25 实锤过两回）
//
// ① 分享卡片：「主人发的这个我看不到内容呀，链接没打开」——主人当场无语。
//    根因不是模型不会，是占位符（[分享视频]）本来就拿不到正文，她只能顺着说"看不见"。
//    ⚠️ 10-26 修方向：上一版的对策是"想知道细节就问标题"，结果她**一直**索要标题
//       （用户投诉：「一直叫我念标题给她」）。现在私信卡片会被点开抽帧、真的看完视频
//       （见 douyin_interact.py card-open），所以兜底改成"就按看到的聊"，不许要标题。
// ② 时间说法不在这支里（见 timefix.mjs）。

const BLIND = /看不到|看不见|打不开|没打开|内容是空|内容为空|显示不出|没显示出来|空白的?呀|链接(坏|失效)/
// 她"向主人索要内容"的句式：标题念给我/发我标题/分享的哪个呀 —— 现在她自己能看，这句同样要清掉。
const ASKING = /念.{0,6}标题|标题.{0,8}(念给|给(我|你)听|发给我|给我看)|发我标题|分享的哪个呀|你发的哪个/

/** 这句是不是在"喊看不见"。 */
export function looksBlind(text) {
  return BLIND.test(String(text ?? ''))
}

/** 这句是不是在向主人索要标题/链接（10-26 新增：她自己能看视频了，不该再问）。 */
export function looksAsking(text) {
  return ASKING.test(String(text ?? ''))
}

/** 兜底改写：把"看不到内容"那半句删掉，其余原样保留。
 *  删空了就换成一句"我自己再看看"，**不再**改成问标题（那是上一版的病根）。 */
export function askInstead(text) {
  let s = String(text ?? '')
  if (!looksBlind(s) && !looksAsking(s)) return s
  s = s.replace(/[^。！？\n]*(?:看不到|看不见|打不开|没打开|内容是空|内容为空|显示不出|没显示出来|空白的?呀|链接(?:坏|失效))[^。！？\n]*[。！？]?/g, '')
  s = s.replace(/[^。！？\n]*(?:念.{0,6}标题|标题.{0,8}(?:念给|给(?:我|你)听|发给我|给我看)|发我标题|分享的哪个呀|你发的哪个)[^。！？\n]*[。！？]?/g, '')
  s = s.replace(/^\s*[\n。，、]+/, '').trim()
  return s || '等我再瞅两眼'
}

/** 给 prompt 用的一句硬约束（分享/卡片场景）。 */
export function noBlindHint() {
  return '（主人分享的是**给你的东西**，你手上已经有了这条视频的标题/画面（见上面的【主人分享的视频：…】）。'
    + '就按你看到的聊：点一个画面细节、吐槽一句、联想到你馋的东西。'
    + '**绝对不要**说"看不到内容""链接打不开""内容是空的""我这边显示不出来"，'
    + '也**不要**向他要标题/链接（"标题念给我听""发我标题""你发的哪个"）—— 你自己看得见。）'
}